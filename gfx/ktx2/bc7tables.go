// bc7Lerp interpolates one channel between two endpoints at a weight in
// sixty-fourths, rounding the way the format says.
func bc7Lerp(e0, e1, w int) uint8 {
	return uint8(((64-w)*e0 + w*e1 + 32) >> 6)
}
